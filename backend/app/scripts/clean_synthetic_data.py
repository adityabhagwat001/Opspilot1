"""
OpsPilot Synthetic Data Cleaner & Live Database Sanitizer
Safely detects, previews, and purges mock/synthetic test artifacts from opspilot_system.db
while strictly preserving genuine GitHub incidents, repository configurations, integrations, and users.
Includes automated timestamped backup and dry-run safety modes.
"""

import sys
import os
import shutil
import sqlite3
import datetime
import argparse

DB_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "opspilot_system.db"))

def create_backup(db_path: str) -> str:
    """Creates a timestamped snapshot backup before any mutation."""
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_path = f"{db_path}.backup.{timestamp}"
    shutil.copy2(db_path, backup_path)
    return backup_path

def is_synthetic_failure(row: dict) -> bool:
    """Classifies whether a failure record was generated by automated testing."""
    run_id = row.get("run_id") or 0
    str_run_id = str(run_id)
    repo = (row.get("repo_full_name") or "").lower()
    fail_id = (row.get("id") or "").lower()
    commit_sha = (row.get("commit_sha") or "").lower()
    actor = (row.get("actor") or "").lower()

    # 1. Known synthetic run IDs used in tests (9988..., 77112233)
    if str_run_id.startswith("9988") or run_id == 77112233:
        return True

    # 2. Mock enterprise organization used in test fixtures
    if "enterprise-ops" in repo or "auth-service" in repo:
        return True

    # 3. Test fixtures prefix patterns
    if any(fail_id.startswith(p) for p in ["fail-test-", "fail-audit-", "fail-verif-", "fail-fail-", "wf-lifecycle-", "wf-phase5-"]):
        return True

    # 4. Known synthetic commit hashes from tests
    if commit_sha.startswith("a1b2c3d4e5f6") or commit_sha.startswith("f1f2f3f4f5f6") or commit_sha.startswith("e1e2e3e4e5e6") or commit_sha.startswith("c1d2e3f4a5b6"):
        return True

    # 5. Generic test runner actor
    if actor in ["test-runner", "github-actor"]:
        return True

    return False

def clean_database(dry_run: bool = False, skip_backup: bool = False):
    if not os.path.exists(DB_PATH):
        print(f"[ERROR] Database file not found at: {DB_PATH}")
        sys.exit(1)

    print("=" * 70)
    print("OPSPILOT DATABASE SANITIZATION & SYNTHETIC DATA CLEANER")
    print(f"Target Database: {DB_PATH}")
    print(f"Mode: {'DRY RUN (Preview Only - No changes made)' if dry_run else 'ACTIVE PURGE'}")
    print("=" * 70)

    if not dry_run and not skip_backup:
        backup_file = create_backup(DB_PATH)
        print(f"[BACKUP] Created database snapshot at: {backup_file}")

    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    c = conn.cursor()

    # 1. Scan workflow_failures
    c.execute("SELECT id, repo_full_name, run_id, workflow_name, commit_sha, actor, status, resolution_status FROM workflow_failures")
    all_failures = [dict(row) for row in c.fetchall()]

    synthetic_failures = [f for f in all_failures if is_synthetic_failure(f)]
    real_failures = [f for f in all_failures if not is_synthetic_failure(f)]

    synthetic_fail_ids = set(f["id"] for f in synthetic_failures)
    synthetic_run_ids = set(str(f["run_id"]) for f in synthetic_failures if f.get("run_id"))

    print(f"\n[FAILURES SCAN] Total: {len(all_failures)} | Synthetic/Test: {len(synthetic_failures)} | Legitimate/Real: {len(real_failures)}")

    if real_failures:
        print("\nLegitimate Real GitHub Failures to Preserve:")
        for rf in real_failures:
            print(f"  + PRESERVED: ID={rf['id']} | Repo={rf['repo_full_name']} | Run=#{rf['run_id']} | Status={rf['status']} | Resolution={rf['resolution_status']}")

    if synthetic_failures:
        print("\nSynthetic/Test Failures Identified for Cleanup:")
        for sf in synthetic_failures[:10]:
            print(f"  - PURGE: ID={sf['id']} | Repo={sf['repo_full_name']} | Run=#{sf['run_id']} | Commit={sf['commit_sha'][:8]} | Actor={sf['actor']}")
        if len(synthetic_failures) > 10:
            print(f"  ... and {len(synthetic_failures) - 10} more synthetic failure records.")

    # 2. Scan fix_proposals
    c.execute("SELECT id, failure_id, repo_full_name, fix_branch, title, status FROM fix_proposals")
    all_proposals = [dict(row) for row in c.fetchall()]

    synthetic_proposals = []
    real_proposals = []
    for p in all_proposals:
        f_id = p.get("failure_id")
        branch = p.get("fix_branch") or ""
        repo = p.get("repo_full_name") or ""
        is_synth = (
            f_id in synthetic_fail_ids or
            "enterprise-ops" in repo or
            any(rid in branch for rid in synthetic_run_ids) or
            "9988" in branch or
            "test" in branch.lower()
        )
        if is_synth:
            synthetic_proposals.append(p)
        else:
            real_proposals.append(p)

    synthetic_prop_ids = set(p["id"] for p in synthetic_proposals)
    print(f"\n[PROPOSALS SCAN] Total: {len(all_proposals)} | Synthetic: {len(synthetic_proposals)} | Legitimate: {len(real_proposals)}")
    if real_proposals:
        for rp in real_proposals:
            print(f"  + PRESERVED PROPOSAL: ID={rp['id']} | Repo={rp['repo_full_name']} | Branch={rp['fix_branch']} | Status={rp['status']}")

    # 3. Scan approval_requests linked to synthetic proposals or failures
    c.execute("SELECT id, execution_id, target_resource, canonical_action_arguments, approval_status FROM approval_requests")
    all_approvals = [dict(row) for row in c.fetchall()]
    synthetic_approvals = []
    for a in all_approvals:
        args_str = a.get("canonical_action_arguments") or ""
        target = a.get("target_resource") or ""
        is_synth = (
            any(pid in args_str for pid in synthetic_prop_ids) or
            any(rid in target for rid in synthetic_run_ids) or
            any(rid in args_str for rid in synthetic_run_ids) or
            "enterprise-ops" in target or
            "enterprise-ops" in args_str or
            "9988" in target or
            "9988" in args_str
        )
        if is_synth:
            synthetic_approvals.append(a)

    print(f"[APPROVALS SCAN] Total: {len(all_approvals)} | Synthetic: {len(synthetic_approvals)} | Legitimate: {len(all_approvals) - len(synthetic_approvals)}")

    # 4. Scan in_app_notifications
    c.execute("SELECT id, title, message, link FROM in_app_notifications")
    all_notifs = [dict(row) for row in c.fetchall()]
    synthetic_notifs = [
        n for n in all_notifs
        if (n.get("link") in synthetic_fail_ids) or
           (n.get("link") in synthetic_prop_ids) or
           any(rid in (n.get("message") or "") for rid in synthetic_run_ids) or
           "enterprise-ops" in (n.get("message") or "") or
           "9988" in (n.get("message") or "")
    ]
    print(f"[NOTIFICATIONS SCAN] Total: {len(all_notifs)} | Synthetic: {len(synthetic_notifs)} | Legitimate: {len(all_notifs) - len(synthetic_notifs)}")

    if dry_run:
        print("\n[DRY RUN SUMMARY] No changes were applied. Run without --dry-run to execute purge.")
        conn.close()
        return

    # Execute purge
    print("\n[PURGING SYNTHETIC ARTIFACTS]")
    if synthetic_fail_ids:
        c.executemany("DELETE FROM workflow_failures WHERE id = ?", [(fid,) for fid in synthetic_fail_ids])
        print(f"  - Removed {len(synthetic_fail_ids)} synthetic workflow failure rows.")

    if synthetic_prop_ids:
        c.executemany("DELETE FROM fix_proposals WHERE id = ?", [(pid,) for pid in synthetic_prop_ids])
        print(f"  - Removed {len(synthetic_prop_ids)} synthetic fix proposal rows.")

    if synthetic_approvals:
        c.executemany("DELETE FROM approval_requests WHERE id = ?", [(a["id"],) for a in synthetic_approvals])
        print(f"  - Removed {len(synthetic_approvals)} synthetic approval request rows.")

    if synthetic_notifs:
        c.executemany("DELETE FROM in_app_notifications WHERE id = ?", [(n["id"],) for n in synthetic_notifs])
        print(f"  - Removed {len(synthetic_notifs)} synthetic notification rows.")

    conn.commit()
    conn.close()
    print("\n[COMPLETED] Database successfully cleaned. Only genuine, verified operational records remain.")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="OpsPilot Synthetic Data Cleaner")
    parser.add_argument("--dry-run", action="store_true", help="Preview records to be cleaned without deleting")
    parser.add_argument("--no-backup", action="store_true", help="Skip automatic database backup")
    args = parser.parse_args()

    clean_database(dry_run=args.dry_run, skip_backup=args.no_backup)
