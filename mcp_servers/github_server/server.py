@mcp.tool()
async def list_repositories(visibility: str = "all", per_page: int = 10) -> Dict[str, Any]:
    """
    List repositories accessible by the configured GitHub token or user account.
    """
    token = os.getenv("GITHUB_TOKEN", "")
    if not token:
        return {
            "error": "GITHUB_AUTH_REQUIRED: GITHUB_TOKEN is not configured in environment or settings.",
            "status": "UNAUTHENTICATED"
        }
    async with get_github_client(token) as client:
        resp = await client.get("/user/repos", params={"visibility": visibility, "per_page": per_page, "sort": "updated"})
        if resp.status_code != 200:
            return {"error": f"GitHub API error ({resp.status_code}): {resp.text}"}
        repos = resp.json()
        return {
            "total_returned": len(repos),
            "repositories": [
                {
                    "id": r.get("id"),
                    "name": r.get("name"),
                    "full_name": r.get("full_name"),
                    "private": r.get("private"),
                    "description": r.get("description"),
                    "html_url": r.get("html_url"),
                    "open_issues_count": r.get("open_issues_count"),
                    "default_branch": r.get("default_branch"),
                    "updated_at": r.get("updated_at")
                }
                for r in repos
            ]
        }

@mcp.tool()
async def get_repository_details(owner: str, repo: str) -> Dict[str, Any]:
    """
    Get metadata, stars, forks, and health of a specific GitHub repository.
    """
    token = os.getenv("GITHUB_TOKEN", "")
    async with get_github_client(token) as client:
        resp = await client.get(f"/repos/{owner}/{repo}")
        if resp.status_code == 404:
            return {"error": f"Repository '{owner}/{repo}' not found or inaccessible."}
        if resp.status_code != 200:
            return {"error": f"GitHub API error ({resp.status_code}): {resp.text}"}
        data = resp.json()
        return {
            "full_name": data.get("full_name"),
            "description": data.get("description"),
            "html_url": data.get("html_url"),
            "stars": data.get("stargazers_count"),
            "forks": data.get("forks_count"),
            "open_issues": data.get("open_issues_count"),
            "default_branch": data.get("default_branch"),
            "language": data.get("language")
        }

@mcp.tool()
async def list_issues(
    owner: str,
    repo: str,
    state: str = "open",
    labels: Optional[str] = None,
    per_page: int = 15
) -> Dict[str, Any]:
    """
    Retrieve live issues from a GitHub repository, filtered by state (open, closed, all) and labels.
    """
    token = os.getenv("GITHUB_TOKEN", "")
    params = {"state": state, "per_page": per_page, "sort": "updated", "direction": "desc"}
    if labels:
        params["labels"] = labels

    async with get_github_client(token) as client:
        resp = await client.get(f"/repos/{owner}/{repo}/issues", params=params)
        if resp.status_code != 200:
            return {"error": f"GitHub API error ({resp.status_code}): {resp.text}"}
        
        raw_issues = resp.json()
        # Filter out pull requests which GitHub includes in issues endpoint
        issues = [i for i in raw_issues if "pull_request" not in i]
        return {
            "owner": owner,
            "repo": repo,
            "count": len(issues),
            "issues": [
                {
                    "number": i.get("number"),
                    "title": i.get("title"),
                    "state": i.get("state"),
                    "user": i.get("user", {}).get("login"),
                    "labels": [l.get("name") for l in i.get("labels", [])],
                    "comments_count": i.get("comments"),
                    "created_at": i.get("created_at"),
                    "updated_at": i.get("updated_at"),
                    "html_url": i.get("html_url"),
                    "body_snippet": (i.get("body") or "")[:200]
                }
                for i in issues
            ]
        }

